
library(shiny)

ui <- fluidPage(
  titlePanel("Car Fuel Efficiency Predictor"),
  
  sidebarLayout(
    sidebarPanel(
      h4("Enter Car Details"),
      
      sliderInput(
        "wt",
        "Car Weight (in 1000 lbs):",
        min = 1.5, max = 5.5,
        value = 3.0, step = 0.1
      ),
      
      sliderInput(
        "hp",
        "Horsepower:",
        min = 50, max = 335,
        value = 120, step = 5
      ),
      
      selectInput(
        "cyl",
        "Number of Cylinders:",
        choices = c("4", "6", "8"),
        selected = "6"
      ),
      
      helpText(
        "Adjust the inputs to estimate your car's fuel efficiency."
      )
    ),
    
    mainPanel(
      h3("Prediction Result"),
      textOutput("prediction"),
      
      plotOutput("comparison", height = "350px"),
      
      
      h4("About This Application"),
      
      p(
        "The Car Fuel Efficiency Predictor estimates the fuel
  efficiency of a car using a linear regression model."
      ),
      
      p(
        "The model is trained on the mtcars dataset included
  with R. This dataset contains information about cars,
  including their weight, horsepower, cylinders, and
  miles per gallon (MPG)."
      ),
      
      h4("How to Use the Application"),
      
      tags$ol(
        tags$li(
          "Use the Car Weight slider to select a weight
    between 1.5 and 5.5 thousand pounds."
        ),
        tags$li(
          "Use the Horsepower slider to select a value
    between 50 and 335."
        ),
        tags$li(
          "Select the number of cylinders: 4, 6, or 8."
        ),
        tags$li(
          "Read the predicted fuel efficiency shown
    under Prediction Result."
        ),
        tags$li(
          "View the chart to compare your prediction
    with the average MPG of cars grouped by cylinders."
        )
      ),
      
      h4("Understanding the Results"),
      
      p(
        "MPG means miles per gallon. A higher MPG generally
  means a car travels farther using the same amount of fuel."
      ),
      
      p(
        "The predicted MPG is an estimate generated by the
  regression model. It is not a guarantee of actual
  fuel consumption."
      ),
      
      h4("Limitations"),
      
      p(
        "The model is trained on a small historical dataset.
  Its predictions may not represent modern vehicles
  or real-world driving conditions. Factors such as
  road conditions, maintenance, traffic, and driving
  style are not included in this model."
      ),
      
      h4("Technology Used"),
      
      p(
        "This application uses R, Shiny, the built-in mtcars
  dataset, and a linear regression model."
      )
       ,
      p(
        "The prediction uses a linear regression model trained ",
        "on the built-in mtcars dataset. Results are estimates, ",
        "not guaranteed real-world fuel economy."
      )
    )
  )
)

